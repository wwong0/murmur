// Read-only: export the retained pitch-disabled correction trajectory for the
// listening comparison. Usage, from app/: node listening/extract-trajectory.mjs
// Selection is fixed, not chosen by ear: of the four candidate clients in the
// passing pitch-disabled batch, take the one with the MOST correction, measured
// as the integral of |rate - 1| over its capture window. Times are relative to
// that client's capture-window start; rates are exactly what the element was set to.
import fs from 'node:fs';
import path from 'node:path';

const BATCH = 'results/4e-browser-comparison-2026-09-11T05-35-04.025Z-26420-ea0f957f';
const readEvents = (dir) => fs.readFileSync(path.join(dir, 'events.ndjson'), 'utf8')
  .split('\n').filter(Boolean).map((line) => JSON.parse(line));

const clients = [];
for (const trial of fs.readdirSync(BATCH).filter((name) => /^trial-\d+-C$/.test(name)).sort()) {
  for (const client of fs.readdirSync(path.join(BATCH, trial)).filter((name) => name.startsWith('client-')).sort()) {
    const dir = path.join(BATCH, trial, client);
    const { startMs, endMs } = JSON.parse(fs.readFileSync(path.join(dir, 'client.json'), 'utf8')).window;
    const events = readEvents(dir);
    const pitch = events.find((event) => event.kind === 'construction' && event.factory === 'preservesPitch');
    const calls = events.filter((event) => event.kind === 'rate-call' && event.rateAfter !== event.rateBefore)
      .sort((a, b) => a.atMs - b.atMs);
    let rate = 1;
    for (const call of calls) if (call.atMs < startMs) rate = call.rateAfter;
    const initialRate = rate;
    const writes = calls.filter((call) => call.atMs >= startMs && call.atMs < endMs);
    let integralMs = 0;
    let at = startMs;
    for (const call of writes) {
      integralMs += Math.abs(rate - 1) * (call.atMs - at);
      rate = call.rateAfter;
      at = call.atMs;
    }
    integralMs += Math.abs(rate - 1) * (endMs - at);
    clients.push({
      client: `${trial}/${client}`,
      preservesPitch: pitch?.readback ?? null,
      initialRate,
      integralMs,
      writes: writes.map((call) => ({ tMs: +(call.atMs - startMs).toFixed(1), rate: call.rateAfter })),
    });
  }
}

const chosen = clients.reduce((best, entry) => (entry.integralMs > best.integralMs ? entry : best));
if (chosen.preservesPitch !== false) throw new Error(`${chosen.client} did not run with pitch preservation disabled`);
const out = {
  batch: path.basename(BATCH),
  client: chosen.client,
  selection: 'most integrated |rate - 1| of the four candidate clients',
  candidates: clients.map(({ client, integralMs, writes }) => ({ client, integralMs: +integralMs.toFixed(1), writes: writes.length })),
  initialRate: chosen.initialRate,
  lastWriteMs: chosen.writes.at(-1).tMs,
  writes: chosen.writes,
};
const target = path.join('listening', 'trajectory.js');
fs.writeFileSync(target, `// Generated by extract-trajectory.mjs from retained evidence. Do not edit.\nwindow.TRAJECTORY = ${JSON.stringify(out, null, 1)};\n`);
console.log(`${out.client}: ${out.writes.length} writes to ${out.lastWriteMs} ms, integral ${chosen.integralMs.toFixed(1)} ms -> ${target}`);
console.log(out.candidates.map((entry) => `  ${entry.client} ${entry.integralMs} ms over ${entry.writes} writes`).join('\n'));
